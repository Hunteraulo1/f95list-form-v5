type Execute = (sql: string, params?: unknown[]) => Promise<unknown>;

//? Remet en place tout ce qui relie les tags de la base à ceux de F95zone. À rejouer chaque fois que
//? `game_tags` est reconstruite (reprise de la v4) ; sans effet sur ce qui est déjà en place.
//?  1. `f95_id` : un tag du même nom le reçoit (sur sa ligne la plus ancienne, `f95_id` est unique),
//?     un tag absent est créé ;
//?  2. `active` : faux pour les tags à classer, ni tag F95zone ni connus du dictionnaire ;
//?  3. `f95_tag_id` : les autres tags connus du dictionnaire pointent leur tag F95zone ;
//?  4. `game.tags_f95` : la version filtrée des tags de chaque jeu.
export const setupF95Tags = async (execute: Execute) => {
  for (const [id, name] of F95_TAGS) {
    await execute(
      'update `game_tags` set `f95_id` = ? where `id` = (select `id` from (select min(`id`) as `id` from `game_tags` where `name` = ?) as `oldest`) and `f95_id` is null and not exists (select 1 from (select 1 from `game_tags` where `f95_id` = ?) as `taken`)',
      [id, name, id],
    );
    await execute(
      'insert into `game_tags` (`name`, `f95_id`) select ?, ? from dual where not exists (select 1 from `game_tags` where `name` = ? or `f95_id` = ?)',
      [name, id, name, id],
    );
  }

  const known = Object.keys(F95_TAG_ID_BY_NAME);
  await execute(
    `update \`game_tags\` set \`active\` = false where \`f95_id\` is null and \`f95_tag_id\` is null and \`name\` not in (${known.map(() => '?').join(', ')})`,
    known,
  );

  for (const [name, f95Id] of Object.entries(F95_TAG_ID_BY_NAME)) {
    if (f95Id === 0) continue;

    await execute(
      'update `game_tags` `t` join `game_tags` `f` on `f`.`f95_id` = ? set `t`.`f95_tag_id` = `f`.`id` where `t`.`f95_id` is null and `t`.`f95_tag_id` is null and `t`.`name` = ?',
      [f95Id, name],
    );
  }

  await execute(
    'update `game` `g` set `g`.`tags_f95` = coalesce((select json_arrayagg(distinct coalesce(`t`.`f95_id`, `l`.`f95_id`) order by coalesce(`t`.`f95_id`, `l`.`f95_id`)) from `game_game_tags` `gt` join `game_tags` `t` on `t`.`id` = `gt`.`game_tag_id` left join `game_tags` `l` on `l`.`id` = `t`.`f95_tag_id` where `gt`.`game_id` = `g`.`id` and coalesce(`t`.`f95_id`, `l`.`f95_id`) is not null), json_array())',
  );
};
